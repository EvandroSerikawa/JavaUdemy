package Fundamentos;
public class TipoString {
    public static void main(String[] args) {
        System.out.println("Hello World!".charAt(3));

        //Funcionalidades pertencentes ao tipo String

        String s = "Boa tarde.";
        System.out.println(s.concat("!!!"));
        System.out.println(s + "*****");

        //Tipo String = objeto imutável
        //Não é possivel alterar o valor inicial atribuido a variável




    }
}
